package no.nav.helsemelding.inbound.model

import no.nav.helsemelding.inbound.metrics.ErrorTypeTag

enum class ProcessingResult {
    SUCCESS,
    IGNORED_APPREC,
    RETRIEVING_BUSINESS_DOCUMENT_FAILED,
    SPLITTING_MESSAGE_FAILED,
    SAVING_ATTACHMENTS_FAILED,
    PUBLISHING_TO_KAFKA_FAILED,
    MARKING_MESSAGE_AS_DOWNLOADED_FAILED,
    DECODING_BUSINESS_DOCUMENT_FAILED,
    SENDING_APPREC_FAILED,
    EXTRACTING_MESSAGE_ID_FAILED,
    VIRUS_DETECTED,
    VIRUS_SCAN_FAILED,
    DUPLICATE_MESSAGE_DETECTED,
    CALCULATING_CONTENT_HASH_FAILED;

    fun toErrorTypeTag(): ErrorTypeTag = when (this) {
        SUCCESS,
        IGNORED_APPREC -> throw IllegalArgumentException("$this is not a processing failure")
        RETRIEVING_BUSINESS_DOCUMENT_FAILED -> ErrorTypeTag.RETRIEVING_BUSINESS_DOCUMENT_FAILED
        SPLITTING_MESSAGE_FAILED -> ErrorTypeTag.SPLITTING_MESSAGE_FAILED
        SAVING_ATTACHMENTS_FAILED -> ErrorTypeTag.SAVING_ATTACHMENTS_FAILED
        PUBLISHING_TO_KAFKA_FAILED -> ErrorTypeTag.PUBLISHING_TO_KAFKA_FAILED
        MARKING_MESSAGE_AS_DOWNLOADED_FAILED -> ErrorTypeTag.MARKING_MESSAGE_AS_DOWNLOADED_FAILED
        DECODING_BUSINESS_DOCUMENT_FAILED -> ErrorTypeTag.DECODING_BUSINESS_DOCUMENT_FAILED
        SENDING_APPREC_FAILED -> ErrorTypeTag.SENDING_APPREC_FAILED
        EXTRACTING_MESSAGE_ID_FAILED -> ErrorTypeTag.EXTRACTING_MESSAGE_ID_FAILED
        VIRUS_DETECTED -> ErrorTypeTag.VIRUS_DETECTED
        VIRUS_SCAN_FAILED -> ErrorTypeTag.VIRUS_SCAN_FAILED
        DUPLICATE_MESSAGE_DETECTED -> ErrorTypeTag.DUPLICATE_MESSAGE_DETECTED
        CALCULATING_CONTENT_HASH_FAILED -> ErrorTypeTag.CALCULATING_CONTENT_HASH_FAILED
    }
}
